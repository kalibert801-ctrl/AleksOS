#pragma once
// game_genie.h — NES Game Genie code декодирование и патчинг ROM.
//
// Как работает Game Genie:
//   Оригинальный картридж Game Genie вставлялся между игровым картриджем и консолью.
//   Он перехватывал шину CPU и при обращении к определённому адресу подменял возвращаемое
//   значение на запрограммированное (не меняя ROM на картридже).
//
// Мы эмулируем это, патча ROM байты в памяти ПЕРЕД запуском nofrendo.
// Поскольку ROM загружена в PSRAM (ps_malloc), данные доступны для записи.
//
// Кодировка:
//   Алфавит: APZLGITYEOXUKSVN (16 символов = 4 бита каждый)
//   6-символьный код → адрес (15 бит, $8000–$FFFF) + значение (7 бит)
//   8-символьный код → то же + байт сравнения (патчится только если текущий байт = cmp)
//
// Формат iNES ROM:
//   [0..15]  = заголовок (16 байт)
//   [4]      = кол-во PRG ROM банков по 16 КБ
//   [6] бит2 = наличие trainer (512 байт) между заголовком и PRG ROM
//   PRG ROM начинается с байта 16 (или 528 если есть trainer)

#include <stdint.h>

// ── Декодирование одного кода ─────────────────────────────────────────────────
// Возвращает true если код корректный (6 или 8 символов, только GG-алфавит).
// hasCmp=true → 8-символьный код с байтом сравнения.
bool gg_decode(const char *code,
               uint16_t *addr,
               uint8_t  *val,
               uint8_t  *cmp,
               bool     *hasCmp);

// ── Применение всех активных кодов к ROM-буферу ──────────────────────────────
// Вызывается из emu_runner.cpp после загрузки ROM в PSRAM.
// romBuf — указатель на начало iNES ROM (заголовок + PRG + CHR).
// romSize — полный размер буфера.
// Коды берутся из settings.ggCodes[] если settings.ggEnabled != 0.
void gg_apply(uint8_t *romBuf, uint32_t romSize);
