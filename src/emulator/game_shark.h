#pragma once
// game_shark.h — NES Game Shark / Pro Action Replay декодирование.
//
// Как работает Game Shark:
//   Устройство вставлялось между картриджем и консолью.
//   Каждый кадр записывает заданное значение по заданному адресу в RAM NES,
//   переопределяя то что пишет игра.
//
// Формат кода: 6 hex символов  "AAAAVV"
//   AAAA — 16-битный адрес в RAM (0000–FFFF, обычно 0000–07FF или 6000–7FFF)
//   VV   — 8-битное значение для записи
//   Пример: "006309" → каждый кадр записывает 0x09 по адресу $0063

#include <stdint.h>
#include <stdbool.h>

// Декодирует 6-символьный hex-код в адрес и значение.
// Возвращает true если код валидный (ровно 6 hex символов 0-9/A-F).
bool gs_decode(const char *code, uint16_t *addr, uint8_t *val);
