// ── Выбор палитры по индексу (0=default, 1=Nestopia, 2=FCEUX, 3=Virtual) ──
// Возвращает NULL для индекса 0 (оставить стандартную nofrendo палитру).
static inline const rgb_t *nes_palette_get(int idx) {
    switch(idx) {
        case 1: return pal_nestopia;
        case 2: return pal_fceux;
        case 3: return pal_virtual;
        default: return NULL;
    }
}

